def C(cx, cy, r):
    return ('circle', (cx, cy, r))


def DOT(cx, cy, r=0.9):
    return ('dot', (cx, cy, r))


def L(x1, y1, x2, y2):
    return ('line', (x1, y1, x2, y2))


def PL(*pts):
    return ('polyline', pts)


def PG(*pts):
    return ('polygon', pts)


def FP(*pts):
    return ('fpoly', pts)


def R(x, y, w, h, rx=0):
    return ('rect', (x, y, w, h, rx))


def FR(x, y, w, h, rx=0):
    return ('frect', (x, y, w, h, rx))


def A(cx, cy, r, a0, a1):
    return ('arc', (cx, cy, r, a0, a1))


def RAW(d):
    return ('raw', d)


